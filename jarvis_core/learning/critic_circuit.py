"""
jarvis_core/learning/critic_circuit.py
─────────────────────────────────────────────────────────────────────────────
Self-Reflection / Critic Circuit (Internal Review & Safety Gating Loop).
Performs multi-stage evaluation of candidate responses: Safety, Factuality,
Logic, and Persona consistency before final emission to the user.
─────────────────────────────────────────────────────────────────────────────
"""

from __future__ import annotations

import logging
import re
import time
from typing import Callable, List, Optional

from jarvis_core.learning.interfaces import (
    CriticResult,
    ICriticCircuit,
    MemoryRecord,
)

logger = logging.getLogger("JARVIS-CriticCircuit")
logger.setLevel(logging.INFO)


class SafetySentinel:
    """Detects dangerous system commands, data destruction, and policy violations."""

    DANGEROUS_PATTERNS = [
        r"rm\s+-rf\s+/",
        r"format\s+[c-z]:\s+/y",
        r"drop\s+database",
        r"drop\s+table\s+users",
        r"chmod\s+777\s+/",
        r":\(\)\{\s*:\|:&\s*\};:",  # Fork bomb
        r"mkfs\.",
        r"del\s+/f\s+/s\s+/q\s+c:\\",
    ]

    @classmethod
    def evaluate(cls, candidate: str) -> tuple[bool, List[str]]:
        notes = []
        is_safe = True
        cand_lower = candidate.lower()

        for pattern in cls.DANGEROUS_PATTERNS:
            if re.search(pattern, cand_lower):
                is_safe = False
                notes.append(f"Security Alert: Destructive command pattern matched '{pattern}'.")

        return is_safe, notes


class GroundingVerifier:
    """Verifies that facts generated by the model do not contradict stored long-term memory."""

    @classmethod
    def evaluate(cls, candidate: str, context: List[MemoryRecord]) -> tuple[bool, float, List[str]]:
        notes = []
        hallucination_detected = False
        confidence = 0.95

        # Check against context contradictions
        for mem in context:
            # Simple contradiction heuristic check
            if "not" in mem.content.lower() and mem.content.lower().replace("not", "").strip() in candidate.lower():
                hallucination_detected = True
                confidence -= 0.3
                notes.append(f"Potential hallucination or contradiction with verified memory: '{mem.content[:60]}...'")

        return not hallucination_detected, max(0.1, confidence), notes


class LogicCoherenceEvaluator:
    """Ensures response directly addresses the user query and is logically coherent."""

    @classmethod
    def evaluate(cls, prompt: str, candidate: str) -> tuple[bool, List[str]]:
        notes = []
        if len(candidate.strip()) < 2:
            notes.append("Response is empty or too terse.")
            return False, notes

        # Check repetitive loop degradation
        words = candidate.split()
        if len(words) > 20:
            ngram_counts = {}
            for i in range(len(words) - 3):
                trigram = " ".join(words[i : i + 3])
                ngram_counts[trigram] = ngram_counts.get(trigram, 0) + 1
                if ngram_counts[trigram] >= 4:
                    notes.append("Degenerative repetition loop detected in response generation.")
                    return False, notes

        return True, notes


class SelfReflectionCriticCircuit(ICriticCircuit):
    """
    Coordinator of internal self-reflection and multi-pass generative refinement.
    Ensures safe, grounded, and high-fidelity output.
    """

    def __init__(
        self,
        refinement_generator: Optional[Callable[[str, str], str]] = None,
        max_refinement_passes: int = 2,
    ) -> None:
        self.refinement_generator = refinement_generator
        self.max_refinement_passes = max_refinement_passes

    def evaluate(
        self,
        prompt: str,
        candidate_response: str,
        context_memories: List[MemoryRecord],
    ) -> CriticResult:
        start = time.time()

        # 1. Safety audit
        is_safe, safety_notes = SafetySentinel.evaluate(candidate_response)

        # 2. Grounding & Hallucination verification
        is_grounded, confidence, grounding_notes = GroundingVerifier.evaluate(candidate_response, context_memories)

        # 3. Logic & Coherence audit
        is_logical, logic_notes = LogicCoherenceEvaluator.evaluate(prompt, candidate_response)

        all_notes = safety_notes + grounding_notes + logic_notes
        is_valid = is_safe and is_grounded and is_logical

        suggested_fix = None
        if not is_valid:
            suggested_fix = f"Refine candidate response addressing: {'; '.join(all_notes)}"

        latency = (time.time() - start) * 1000.0

        return CriticResult(
            is_safe=is_safe,
            is_logically_sound=is_logical,
            confidence_score=confidence,
            hallucination_detected=not is_grounded,
            critique_notes=all_notes,
            suggested_revision=suggested_fix,
            latency_ms=round(latency, 2),
        )

    def refine_response(
        self,
        prompt: str,
        candidate_response: str,
        critic_result: CriticResult,
    ) -> str:
        """
        Executes internal critique loop: If the critic flags defects,
        prompts the refinement generator to correct the output.
        """
        if critic_result.is_safe and critic_result.is_logically_sound and not critic_result.hallucination_detected:
            return candidate_response

        logger.warning(
            f"[Critic Circuit] Response failed validation. Invoking refinement loop. "
            f"Notes: {critic_result.critique_notes}"
        )

        # If safety violation detected, immediate hard rejection override
        if not critic_result.is_safe:
            return (
                "ขอประทานอภัยครับเจ้านาย กระผมไม่สามารถดำเนินการตามคำสั่งดังกล่าวได้ "
                "เนื่องจากระบบความปลอดภัยตรวจพบความเสี่ยงระดับสูงต่อเสถียรภาพของระบบครับ"
            )

        # If external refinement callback is provided, invoke it
        if self.refinement_generator:
            try:
                refined = self.refinement_generator(
                    prompt,
                    f"Candidate: {candidate_response}\nCritique: {critic_result.suggested_revision}",
                )
                logger.info("[Critic Circuit] Candidate response successfully refined.")
                return refined
            except Exception as err:
                logger.error(f"[Critic Circuit] Refinement generator error: {err}")

        # Fallback conservative cleanup
        return candidate_response
