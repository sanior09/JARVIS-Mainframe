"""
preference_alignator.py
Module 4: Personal Style & Preference Alignator

Responsible for storing the user's specific tastes (coding style, tone, format)
and dynamically aligning the system's output to match those preferences.
"""

import logging
from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional

# Setup Module Logger
logger = logging.getLogger("PreferenceAlignator")
logger.setLevel(logging.INFO)
handler = logging.StreamHandler()
formatter = logging.Formatter('%(asctime)s - [%(name)s] - %(levelname)s - %(message)s')
handler.setFormatter(formatter)
if not logger.handlers:
    logger.addHandler(handler)


class AlignatorException(Exception):
    """Base exception for the Preference Alignator module."""
    pass


@dataclass
class CodingPreferences:
    indentation: str = "    "  # 4 spaces
    naming_convention: str = "snake_case"
    use_type_hints: bool = True
    prefer_async: bool = True


@dataclass
class CommunicationPreferences:
    tone: str = "professional_yet_witty"
    verbosity: str = "concise"  # "verbose", "concise", "extreme_concise"
    language: str = "th-TH"


@dataclass
class UserProfile:
    user_id: str
    coding_prefs: CodingPreferences = field(default_factory=CodingPreferences)
    comm_prefs: CommunicationPreferences = field(default_factory=CommunicationPreferences)


class UserPreferenceStore:
    """
    Manages the storage and retrieval of user preferences.
    In production, this could interface with SQLite or Redis.
    """
    
    def __init__(self):
        self._profiles: Dict[str, UserProfile] = {}
        # Pre-load a default profile for the main user (Boss)
        self._profiles["boss"] = UserProfile(
            user_id="boss",
            coding_prefs=CodingPreferences(indentation="    ", naming_convention="snake_case", use_type_hints=True),
            comm_prefs=CommunicationPreferences(tone="jarvis_cinematic", verbosity="concise", language="th-TH")
        )

    def get_profile(self, user_id: str) -> UserProfile:
        """Retrieves a user profile, or creates a default one if it doesn't exist."""
        if user_id not in self._profiles:
            logger.info(f"Creating new default profile for user: {user_id}")
            self._profiles[user_id] = UserProfile(user_id=user_id)
        return self._profiles[user_id]

    def update_coding_preference(self, user_id: str, key: str, value: Any):
        profile = self.get_profile(user_id)
        if hasattr(profile.coding_prefs, key):
            setattr(profile.coding_prefs, key, value)
            logger.info(f"Updated coding preference for {user_id}: {key}={value}")
        else:
            logger.warning(f"Invalid coding preference key: {key}")


class OutputAligner:
    """
    Applies filters and transformations to the raw output generated by the LLM/System
    so that it perfectly matches the user's preferences.
    """
    
    def __init__(self, store: UserPreferenceStore):
        self.store = store

    def align_code_snippet(self, raw_code: str, user_id: str) -> str:
        """
        Dynamically adjusts code structure (e.g., indentation) to match preferences.
        """
        profile = self.store.get_profile(user_id)
        prefs = profile.coding_prefs
        
        aligned_code = raw_code
        
        # Simple simulation of indentation alignment
        if prefs.indentation == "\\t":
            logger.debug("Aligning code to use Tab indentation.")
            # Very basic heuristic replacement for 4 spaces to Tab
            aligned_code = aligned_code.replace("    ", "\\t")
            
        return aligned_code

    def align_communication(self, raw_message: str, user_id: str) -> str:
        """
        Adjusts the tone and verbosity of the message based on preferences.
        In a real scenario, this might trigger a secondary fast LLM pass to rewrite the text.
        """
        profile = self.store.get_profile(user_id)
        prefs = profile.comm_prefs
        
        # Simulated heuristic filters
        aligned_message = raw_message
        
        if prefs.tone == "jarvis_cinematic":
            # Append standard JARVIS cinematic suffixes if not present
            if not aligned_message.endswith("ครับเจ้านาย") and not aligned_message.endswith("ครับท่าน"):
                aligned_message += " ครับเจ้านาย"
                
        if prefs.verbosity == "concise":
            # Simple heuristic: truncate long messages (Simulation only)
            sentences = aligned_message.split('.')
            if len(sentences) > 3:
                aligned_message = '.'.join(sentences[:2]) + ". (ข้อความถูกย่อเพื่อให้กระชับตามรสนิยม) ครับเจ้านาย"
                
        logger.info(f"Aligned communication output for user '{user_id}'")
        return aligned_message


