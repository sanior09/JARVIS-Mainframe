def trigger_blue_border(action_text):
    """เรียกใช้ระบบ HUD Screen Takeover อย่างเป็นทางการของ JARVIS"""
    try:
        sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'modules')))
        from jarvis_screen_takeover import start_screen_takeover
        start_screen_takeover(action_text)
    except Exception as e:
        logger.error(f"Takeover Error: {e}")

def stop_blue_border():
    try:
        from jarvis_screen_takeover import stop_screen_takeover
        stop_screen_takeover()
    except:
        pass

def do_paint():
    trigger_blue_border("JARVIS AUTOMATION: Drawing in MS Paint")
    import pyautogui
    subprocess.Popen("mspaint.exe")
    time.sleep(2)
    pyautogui.hotkey('win', 'up') # maximize
    time.sleep(1)
    
    # Draw a spiral
    width, height = pyautogui.size()
    center_x, center_y = width // 2, height // 2
    
    pyautogui.moveTo(center_x, center_y)
    distance = 5
    for i in range(30):
        pyautogui.dragRel(distance, 0, duration=0.05)   # right
        distance += 10
        pyautogui.dragRel(0, distance, duration=0.05)   # down
        pyautogui.dragRel(-distance, 0, duration=0.05)  # left
        distance += 10
        pyautogui.dragRel(0, -distance, duration=0.05)  # up
    stop_blue_border()
    return "วาดรูปใน Paint โชว์เรียบร้อยแล้วครับเจ้านาย!"

def do_youtube(keyword):
    trigger_blue_border(f"JARVIS AUTOMATION: Searching YouTube for {keyword}")
    import pyautogui
    import webbrowser
    webbrowser.open("https://www.youtube.com")
    time.sleep(4)
    
    pyautogui.hotkey('ctrl', 'l')
    time.sleep(0.5)
    pyautogui.write(f"https://www.youtube.com/results?search_query={keyword}", interval=0.05)
    pyautogui.press('enter')
    time.sleep(3)
    
    # Click somewhere near the top middle where the first video usually is
    pyautogui.click(pyautogui.size()[0] // 2, pyautogui.size()[1] // 3)
    time.sleep(3)
    pyautogui.press('f') # full screen
    
    stop_blue_border()
    return f"เปิด YouTube หาเพลง {keyword} ให้แบบผีจับเมาส์แล้วครับ!"

def do_excel():
    trigger_blue_border("JARVIS AUTOMATION: Auto Data Entry to Excel")
    try:
        import win32com.client
    except ImportError:
        return "ไม่พบโมดูล win32com ครับ โปรดติดตั้งก่อน (pip install pywin32)"
        
    excel = win32com.client.Dispatch("Excel.Application")
    excel.Visible = True # Show it live!
    wb = excel.Workbooks.Add()
    sheet = wb.ActiveSheet
    
    data = [
        ["วันที่", "รายการ", "รายรับ", "รายจ่าย"],
        ["01/10/2026", "เงินเดือน", 50000, 0],
        ["02/10/2026", "ค่ากาแฟ", 0, 150],
        ["03/10/2026", "ซื้อของซุปเปอร์", 0, 1200],
        ["04/10/2026", "ถูกหวย", 4000, 0],
    ]
    
    for row_idx, row_data in enumerate(data, start=1):
        for col_idx, value in enumerate(row_data, start=1):
            sheet.Cells(row_idx, col_idx).Value = value
            time.sleep(0.3) # Typing effect
            
    sheet.Columns.AutoFit()
    stop_blue_border()
    return "พิมพ์ข้อมูลสรุปยอดบัญชีลง Excel สดๆ ให้ดูเรียบร้อยครับเจ้านาย!"

def do_powerpoint(topic):
    trigger_blue_border(f"JARVIS AUTOMATION: Creating PowerPoint '{topic}'")
    try:
        import win32com.client
    except ImportError:
        return "ไม่พบโมดูล win32com ครับ"
        
    ppt = win32com.client.Dispatch("PowerPoint.Application")
    ppt.Visible = True
    
    presentation = ppt.Presentations.Add(True)
    
    slide = presentation.Slides.Add(1, 1) # Title Slide
    slide.Shapes(1).TextFrame.TextRange.Text = topic
    time.sleep(1)
    slide.Shapes(2).TextFrame.TextRange.Text = "Generated by J.A.R.V.I.S."
    time.sleep(1)
    
    slide2 = presentation.Slides.Add(2, 2) # Title and Text
    slide2.Shapes(1).TextFrame.TextRange.Text = "หัวข้อสำคัญ"
    time.sleep(1)
    
    content = slide2.Shapes(2).TextFrame.TextRange
    content.Text = "1. วิเคราะห์ระบบ\n2. สรุปข้อมูล\n3. จัดทำรายงาน"
    
    stop_blue_border()
    return f"สร้างสไลด์ PowerPoint หัวข้อ {topic} ให้ดูสดๆ แล้วครับ!"

def ghost_automation(args):
    action = args.get('action', '').lower()
    keyword = args.get('keyword', 'Jazz Music')
    
    if action == "paint":
        return do_paint()
    elif action == "youtube":
        return do_youtube(keyword)
    elif action == "excel":
        return do_excel()
    elif action == "powerpoint":
        if keyword == "Jazz Music": keyword = "รายงานผลประกอบการ"
        return do_powerpoint(keyword)
    else:
        return "ไม่รู้จักคำสั่ง Ghost Automation นี้ครับ"
